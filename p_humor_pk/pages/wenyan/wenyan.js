  onLoad() {
    const favs = wx.getStorageSync('wenyanFavs') || [];
    this.setData({ favorites: favs });
  },

  prevItem() {
    let index = this.data.currentIndex - 1;
    if (index < 0) index = this.data.items.length - 1;
    this.setData({ currentIndex: index, showNote: false });
  },

  nextItem() {
    let index = (this.data.currentIndex + 1) % this.data.items.length;
    this.setData({ currentIndex: index, showNote: false });
  },

  toggleNote() {
    this.setData({ showNote: !this.data.showNote });
  },

  toggleFavorite() {
    const index = this.data.currentIndex;
    let favs = this.data.favorites;
    if (favs.includes(index)) {
      favs = favs.filter(i => i !== index);
    } else {
      favs.push(index);
    }
    wx.setStorageSync('wenyanFavs', favs);
    this.setData({ favorites: favs });
    wx.showToast({ title: favs.includes(index) ? '已收藏' : '已取消', icon: 'none' });
  },

  goBack() {
    wx.navigateBack();
  },

  touchStart(e) {
    this.setData({ startX: e.touches[0].clientX });
  },

  touchEnd(e) {
    const endX = e.changedTouches[0].clientX;
    const diff = this.data.startX - endX;
    if (Math.abs(diff) > 50) {
      if (diff > 0) this.nextItem();
      else this.prevItem();
    }
  }
